import java.util.Arrays;

public class Leetcode_977_Squares_of_a_Sorted_Array {
    public static void main(String[] args){
        int [] arr = {-4,-1,0,3,10};
        Arrays.sort(arr);

        for (int i = 0; i < arr.length; i++) {
            System.out.print(arr[i]+" ");
        }
    }
}
